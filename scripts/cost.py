"""Rupees per photo at Gemini's PAID-tier prices, from the tokens measured in cache/extractions/.

Development runs on the free tier; production would not, so the memo prices the measured
tokens at the paid Standard rates. Thinking tokens are billed as output.

Usage: python scripts/cost.py --usd-inr <rupees per dollar, e.g. the day's RBI reference rate>
The exchange rate is an input on purpose: state the rate and its date wherever the number is quoted.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]

# USD per 1M tokens, paid tier (Standard), from https://ai.google.dev/gemini-api/docs/pricing
# (page "Last updated 2026-10-14 UTC", read 2026-10-14). 3.8 Flash rises to $1.50 / $7.50 on 2027-01-01.
PRICES = {
    "gemini-3.8-flash": {"input": 0.75, "output": 3.75},
    "gemini-3.6-flash": {"input": 0.75, "output": 3.75},
    "gemini-3.5-flash-lite": {"input": 0.30, "output": 2.50},
    "gemini-3.1-flash-lite": {"input": 0.25, "output": 1.50},
}
PRICES_SOURCE = "https://ai.google.dev/gemini-api/docs/pricing (last updated 2026-10-14)"


def photo_tokens(records: list[dict]) -> pd.DataFrame:
    """One row per photo: every call it took (retries included), summed."""
    rows = []
    for rec in records:
        passes = rec.get("passes", [])
        rows.append({"file": rec["file"], "model": rec.get("model", ""), "calls": len(passes),
                     "input": sum(p.get("input_tokens", 0) for p in passes),
                     "output": sum(p.get("output_tokens", 0) + p.get("thinking_tokens", 0) for p in passes)})
    return pd.DataFrame(rows)


FX_SOURCE_DEFAULT = "rate supplied by the user"
CLERK_COST_MONTH = 2 * 38_000      # two clerks, loaded (email thread)
CLAIMS_MONTH = 2_400               # photo claims a month, company-wide
CLERK_MIN_PER_CLAIM = 3.5          # typing + checking one claim
CLERK_HOURS_MONTH = 2 * 176        # 22 days x 8 h, two clerks


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--usd-inr", type=float, default=None,
                    help="rupees per US dollar; quote its date. Without it, prices are shown in USD only")
    ap.add_argument("--fx-source", default=FX_SOURCE_DEFAULT, help="where and when the rate is from")
    ap.add_argument("--out", type=Path, default=None, help="also write the result as markdown, e.g. reports/cost.md")
    ap.add_argument("--cache-dir", type=Path, default=REPO / "cache" / "extractions")
    args = ap.parse_args()

    records = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(args.cache_dir.glob("*.json"))]
    if not records:
        print("No cached extractions yet.")
        return 1
    df = photo_tokens(records)
    fx = args.usd_inr
    lines = ["# Model cost per photo", "",
             "Generated by `scripts/cost.py` from the tokens recorded in `cache/extractions/`.", "",
             f"- Photos measured: {len(df)}; model calls per photo: mean {df['calls'].mean():.2f} "
             "(rotation and JSON retries included).",
             f"- Tokens per photo: input {df['input'].mean():.0f}, output incl. thinking {df['output'].mean():.0f}.",
             f"- Models that produced them: {', '.join(f'{m} x{n}' for m, n in df['model'].value_counts().items())}.",
             f"- Prices: paid tier (Standard), {PRICES_SOURCE}. Development ran on the free tier; production would not.",
             (f"- Exchange rate: USD 1 = Rs {fx} ({args.fx_source})." if fx else "- No exchange rate given: USD only."),
             "", "| model | USD per photo | Rs per photo | Rs for 2,400 photos a month |", "|---|---|---|---|"]
    for model, p in PRICES.items():
        usd = (df["input"].mean() * p["input"] + df["output"].mean() * p["output"]) / 1e6
        lines.append(f"| {model} | ${usd:.6f} | " + (f"Rs {usd * fx:.3f} | Rs {usd * fx * CLAIMS_MONTH:,.0f} |" if fx else "- | - |"))
    per_claim_all = CLERK_COST_MONTH / CLAIMS_MONTH
    per_claim_time = CLERK_COST_MONTH / CLERK_HOURS_MONTH / 60 * CLERK_MIN_PER_CLAIM
    lines += ["", "## Against the clerk",
              "", f"- Clerk cost per claim: Rs {per_claim_time:.1f} on time spent (3.5 min at Rs "
              f"{CLERK_COST_MONTH / CLERK_HOURS_MONTH:,.0f}/hour, {CLERK_HOURS_MONTH} clerk-hours a month), "
              f"Rs {per_claim_all:.1f} if all clerk cost is spread over {CLAIMS_MONTH:,} claims.",
              "- Thinking tokens: none measured, because every photo was read by Flash-Lite (3.8 Flash was overloaded). "
              "A 3.8 Flash run would add its thinking tokens to the output side.",
              "- 3.8 Flash prices double on 2027-01-01 (pricing page)."]
    text = "\n".join(lines) + "\n"
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
        print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
